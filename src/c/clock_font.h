static void clock_text(GContext *ctx,const char *s,int x,int y) {
 graphics_context_set_fill_color(ctx,GColorBlack);
 for(;*s;s++) {
  if(*s==':') {
   graphics_fill_rect(ctx,GRect(x,y+8,5,6),0,GCornerNone);
   graphics_fill_rect(ctx,GRect(x,y+22,5,6),0,GCornerNone);
   x+=9;
  } else if(*s>='0' && *s<='9') {
   const uint16_t *glyph=clock_digits[*s-'0'];
   for(int r=0;r<16;r++) for(int c=0;c<9;c++)
    if(glyph[r] & (1<<(8-c))) graphics_fill_rect(ctx,GRect(x+2*c,y+2*r,2,2),0,GCornerNone);
   x+=21;
  }
 }
}
